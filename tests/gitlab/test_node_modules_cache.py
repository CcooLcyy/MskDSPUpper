"""使用隔离目录及 Node/npm 桩验证依赖复用，不下载真实依赖。"""
import importlib.util
import contextlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("ensure_node_modules", ROOT / "scripts/gitlab/ensure_node_modules.py")
CACHE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CACHE)

STUB = r'''
import json
import os
from pathlib import Path
import sys
root = Path.cwd()
state = json.loads((root / "tool-state.json").read_text())
args = sys.argv[2:]
if sys.argv[1] == "node":
    print(json.dumps({"version": state.get("node", "v24.0.0"), "platform": sys.platform, "arch": "x64"}))
elif args == ["--version"]:
    print(state.get("npm", "11.0.0"))
elif args[:2] == ["config", "get"]:
    print(root / (args[2] + ".npmrc"))
elif args == ["ci", "--prefer-offline"]:
    count = root / "install-count"
    count.write_text(str(int(count.read_text()) + 1 if count.exists() else 1))
    modules = root / "node_modules"
    modules.mkdir(exist_ok=True)
    if state.get("fail"):
        (modules / "partial").write_text("partial install")
        sys.exit(7)
    package = json.loads((root / "package.json").read_text())
    installed = {}
    for name, version in {**package.get("dependencies", {}), **package.get("devDependencies", {})}.items():
        target = modules / name
        target.mkdir(parents=True, exist_ok=True)
        (target / "package.json").write_text(json.dumps({"name": name, "version": version}))
        installed["node_modules/" + name] = {"version": version}
    (modules / ".package-lock.json").write_text(json.dumps({"lockfileVersion": 3, "packages": installed}))
else:
    raise RuntimeError("unexpected stub invocation: " + repr(args))
'''


class NodeModulesCacheTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="upper-npm-cache-test-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / "workspace"
        self.root.mkdir()
        (self.root / "package.json").write_text(json.dumps({"version": "0.7.1", "dependencies": {"example": "1.0.0"}, "devDependencies": {"@scope/tool": "2.0.0"}}))
        (self.root / "package-lock.json").write_text('{"lockfileVersion":3,"packages":{}}')
        self.state = self.root / "tool-state.json"
        self.state.write_text("{}")
        stub = self.root / "stub.py"
        stub.write_text(STUB, encoding="utf-8")
        self.tools = {}
        for tool in ("node", "npm"):
            if sys.platform == "win32":
                wrapper = self.root / (tool + ".cmd")
                wrapper.write_text('@echo off\n"%s" "%s" %s %%*\n' % (sys.executable, stub, tool))
            else:
                wrapper = self.root / tool
                wrapper.write_text('#!%s\nimport os\nos.execv(%r, [%r, %r, %r, *__import__("sys").argv[1:]])\n' % (sys.executable, sys.executable, sys.executable, str(stub), tool))
                wrapper.chmod(0o700)
            self.tools[tool] = str(wrapper)

    def run_cache(self, real_probes=False):
        def probe(command, root):
            state = json.loads(self.state.read_text())
            if command[0] == self.tools["node"]:
                return json.dumps({"version": state.get("node", "v24.0.0"), "platform": sys.platform, "arch": "x64"})
            if command[1:] == ["--version"]:
                return state.get("npm", "11.0.0")
            self.assertEqual(command[1:3], ["config", "get"])
            return str(root / (command[3] + ".npmrc"))

        with contextlib.ExitStack() as stack:
            stack.enter_context(patch.object(CACHE.shutil, "which", side_effect=lambda name: self.tools.get(name.removesuffix(".cmd"))))
            if not real_probes:
                # 多次身份变化测试只替换只读探测，npm ci 仍执行真实 .cmd/子进程桩。
                stack.enter_context(patch.object(CACHE, "run_output", side_effect=probe))
            CACHE.ensure(self.root)

    def count(self):
        count = self.root / "install-count"
        return int(count.read_text()) if count.exists() else 0

    def marker(self):
        return self.root / "node_modules" / CACHE.MARKER

    def update_state(self, **values):
        self.state.write_text(json.dumps(values))

    def test_cold_then_warm_reuses_successful_locked_install(self):
        self.run_cache(real_probes=True)
        self.assertTrue(self.marker().is_file())
        self.run_cache(real_probes=True)
        self.assertEqual(self.count(), 1)

    def test_lock_change_reinstalls(self):
        self.run_cache()
        (self.root / "package-lock.json").write_text('{"lockfileVersion":3,"packages":{},"changed":true}')
        self.run_cache()
        self.assertEqual(self.count(), 2)

    def test_node_and_npm_version_changes_reinstall(self):
        self.run_cache()
        self.update_state(node="v24.1.0")
        self.run_cache()
        self.update_state(node="v24.1.0", npm="11.1.0")
        self.run_cache()
        self.assertEqual(self.count(), 3)

    def test_project_version_only_does_not_reinstall(self):
        self.run_cache()
        path = self.root / "package.json"
        value = json.loads(path.read_text())
        value["version"] = "0.7.1-ci.123+sha.abc"
        path.write_text(json.dumps(value))
        self.run_cache()
        self.assertEqual(self.count(), 1)

    def test_package_dependency_change_reinstalls(self):
        self.run_cache()
        path = self.root / "package.json"
        value = json.loads(path.read_text())
        value["dependencies"]["example"] = "1.1.0"
        path.write_text(json.dumps(value))
        self.run_cache()
        self.assertEqual(self.count(), 2)

    def test_npmrc_and_environment_change_reinstall_without_logging_secret(self):
        import contextlib
        import io
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            self.run_cache()
            (self.root / ".npmrc").write_text("//registry.invalid/:_authToken=secret-for-test\n")
            self.run_cache()
            (self.root / "userconfig.npmrc").write_text("registry=https://registry.invalid/\n")
            self.run_cache()
            with patch.dict(os.environ, {"NPM_CONFIG_LEGACY_PEER_DEPS": "true"}):
                self.run_cache()
        self.assertEqual(self.count(), 4)
        self.assertNotIn("secret-for-test", output.getvalue())
        self.assertNotIn("registry.invalid", output.getvalue())
        self.assertNotIn("secret-for-test", self.marker().read_text())

    def test_missing_hidden_lock_reinstalls(self):
        self.run_cache()
        (self.root / "node_modules/.package-lock.json").unlink()
        self.run_cache()
        self.assertEqual(self.count(), 2)

    def test_missing_top_level_package_reinstalls(self):
        self.run_cache()
        (self.root / "node_modules/@scope/tool/package.json").unlink()
        self.run_cache()
        self.assertEqual(self.count(), 2)

    def test_changed_package_version_reinstalls(self):
        self.run_cache()
        (self.root / "node_modules/example/package.json").write_text('{"version":"9.9.9"}')
        self.run_cache()
        self.assertEqual(self.count(), 2)

    def test_unmarked_old_node_modules_is_not_trusted(self):
        self.run_cache()
        self.marker().unlink()
        self.run_cache()
        self.assertEqual(self.count(), 2)

    def test_failed_reinstall_invalidates_success_and_retries(self):
        self.run_cache()
        self.update_state(node="v25.0.0", fail=True)
        with self.assertRaisesRegex(RuntimeError, "npm ci"):
            self.run_cache()
        self.assertFalse(self.marker().exists())
        self.update_state(node="v25.0.0")
        self.run_cache()
        self.run_cache()
        self.assertEqual(self.count(), 3)

    def make_directory_link(self, link, target):
        if sys.platform == "win32":
            result = subprocess.run(["cmd.exe", "/d", "/c", "mklink", "/J", str(link), str(target)], capture_output=True)
            self.assertEqual(result.returncode, 0, result.stderr)
        else:
            link.symlink_to(target, target_is_directory=True)

    def test_external_node_modules_link_is_rejected_before_npm(self):
        external = Path(self.temporary.name) / "external"
        external.mkdir()
        sentinel = external / "do-not-touch"
        sentinel.write_text("preserve")
        self.make_directory_link(self.root / "node_modules", external)
        with self.assertRaisesRegex(RuntimeError, "链接"):
            self.run_cache()
        self.assertEqual(self.count(), 0)
        self.assertEqual(sentinel.read_text(), "preserve")

    def test_external_nested_link_is_rejected_before_hit_or_reinstall(self):
        self.run_cache()
        external = Path(self.temporary.name) / "external"
        external.mkdir()
        self.make_directory_link(self.root / "node_modules/escaped", external)
        with self.assertRaisesRegex(RuntimeError, "链接"):
            self.run_cache()
        self.assertEqual(self.count(), 1)

    def test_unsafe_package_name_rejected_without_cache_marker(self):
        (self.root / "package.json").write_text('{"dependencies":{"../escaped":"1.0.0"}}')
        # 在调用 npm 前验证边界，不能由桩或真实 npm 写到目录外。
        with self.assertRaisesRegex(RuntimeError, "依赖名"):
            self.run_cache()
        self.assertFalse(self.marker().exists())
        self.assertEqual(self.count(), 0)


if __name__ == "__main__":
    unittest.main()
