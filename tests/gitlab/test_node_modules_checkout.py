"""使用真实 Git 清理验证仅保留仓库根的前端依赖缓存。"""
from pathlib import Path
import re
import shlex
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


class CheckoutCacheTests(unittest.TestCase):
    def test_checkout_keeps_only_root_node_modules(self):
        config = (ROOT / ".gitlab-ci.yml").read_text(encoding="utf-8")
        flags = shlex.split(re.search(r'GIT_CLEAN_FLAGS: "([^"\n]+)"', config).group(1))
        with tempfile.TemporaryDirectory(prefix="upper-checkout-cache-") as temporary:
            workspace = Path(temporary).resolve()
            subprocess.run(["git", "init", "--quiet", str(workspace)], check=True)
            for name in ["node_modules/keep", "nested/node_modules/remove", "package/stale"]:
                target = workspace / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text("fixture", encoding="utf-8")
            # 只在刚建立的隔离 Git 工作区执行本次流水线的实际清理参数。
            self.assertEqual((workspace / ".git").parent.resolve(), workspace)
            subprocess.run(["git", "clean", *flags], cwd=workspace, check=True, capture_output=True)
            self.assertTrue((workspace / "node_modules/keep").is_file())
            self.assertFalse((workspace / "nested").exists())
            self.assertFalse((workspace / "package").exists())


if __name__ == "__main__":
    unittest.main()
