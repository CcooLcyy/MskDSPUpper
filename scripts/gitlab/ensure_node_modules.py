"""在持久工作区中复用已验证的 npm ci 安装，不改变锁定安装行为。"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import time

MARKER = ".mskdsp-ci-install.json"
INSTALL_ARGS = ["ci", "--prefer-offline"]
SCHEMA = 1


def digest(data):
    return hashlib.sha256(data).hexdigest()


def encoded(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def run_output(command, root):
    result = subprocess.run(command, cwd=root, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if result.returncode:
        # 配置输出可能含凭据；不把 stdout/stderr 回显到日志。
        raise RuntimeError("读取 Node/npm 环境失败（退出码 %s）" % result.returncode)
    return result.stdout.decode("utf-8-sig").strip()


def safe_tree(modules):
    """npm ci 也不能接触逃出工作区的 junction/symlink。"""
    if not modules.exists() and not modules.is_symlink():
        return
    if not modules.is_dir() or modules.is_symlink() or modules.resolve() != modules.absolute():
        raise RuntimeError("node_modules 必须是工作区内的普通目录，拒绝链接缓存")
    boundary = modules.resolve()
    for directory, directories, files in os.walk(modules, followlinks=False):
        for name in directories + files:
            entry = Path(directory) / name
            metadata = entry.lstat()
            reparse = bool(getattr(metadata, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT)
            if entry.is_symlink() or reparse:
                try:
                    entry.resolve().relative_to(boundary)
                except (ValueError, OSError, RuntimeError):
                    raise RuntimeError("node_modules 含指向缓存目录外的链接，拒绝复用或重装") from None
                # junction 不能交给 os.walk；即使在边界内也拒绝目录链接。
                if entry.is_dir() or reparse:
                    raise RuntimeError("node_modules 含目录链接，拒绝复用或重装")


def dependency_names(package):
    names = set(package.get("dependencies", {})) | set(package.get("devDependencies", {}))
    for name in names | set(package.get("optionalDependencies", {})):
        parts = name.split("/")
        if any(part in ("", ".", "..") or "\\" in part or ":" in part for part in parts):
            raise RuntimeError("package.json 含不安全依赖名")
    return names - set(package.get("optionalDependencies", {}))


def identity(root, npm, node):
    package = json.loads((root / "package.json").read_text(encoding="utf-8"))
    dependency_names(package)
    package.pop("version", None)  # CI 临时版本不影响依赖安装。
    config = {}
    config_paths = [root / ".npmrc"]
    for key in ("userconfig", "globalconfig"):
        path = run_output([npm, "config", "get", key], root)
        if path and path not in ("undefined", "null"):
            config_paths.append(Path(path))
    for index, path in enumerate(config_paths):
        config[str(index)] = digest(path.read_bytes()) if path.is_file() else None
    environment = {key.lower(): value for key, value in os.environ.items()
                   if key.lower().startswith("npm_config_") or key.lower() in ("node_env", "node_options")}
    value = {
        "schema": SCHEMA,
        "lock": digest((root / "package-lock.json").read_bytes()),
        "package": package,
        "config": config,
        "environment": environment,
        "node": json.loads(run_output([node, "-p", "JSON.stringify({version:process.version,platform:process.platform,arch:process.arch})"], root)),
        "npm": run_output([npm, "--version"], root),
        "install": INSTALL_ARGS,
    }
    return digest(encoded(value))


def health(root):
    modules = root / "node_modules"
    hidden = modules / ".package-lock.json"
    if not hidden.is_file():
        raise ValueError("缺少 npm 安装锁记录")
    lock = json.loads(hidden.read_text(encoding="utf-8"))
    if not isinstance(lock.get("packages"), dict):
        raise ValueError("npm 安装锁记录无效")
    # hidden lock 只记录本机实际安装的包；完整锁文件中的其他平台可选包不在这里要求存在。
    for package_path, record in lock["packages"].items():
        parts = package_path.split("/")
        if not package_path.startswith("node_modules/") or any(
                part in ("", ".", "..") or "\\" in part or ":" in part for part in parts):
            raise RuntimeError("npm 安装锁含不安全包路径")
        installed = root.joinpath(*parts, "package.json")
        if not installed.is_file():
            raise ValueError("已安装依赖不完整")
        manifest = json.loads(installed.read_text(encoding="utf-8"))
        if not isinstance(record, dict) or record.get("version") != manifest.get("version"):
            raise ValueError("已安装依赖版本与安装锁记录不符")
    package = json.loads((root / "package.json").read_text(encoding="utf-8"))
    names = dependency_names(package)
    manifests = {}
    for name in sorted(names):
        # 包名来自仓库文件；防止 ../ 或绝对路径越过 node_modules。
        parts = name.split("/")
        if any(part in ("", ".", "..") or "\\" in part or ":" in part for part in parts):
            raise RuntimeError("package.json 含不安全依赖名")
        manifest_path = modules.joinpath(*parts, "package.json")
        if not manifest_path.is_file():
            raise ValueError("顶层依赖不完整")
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        record = lock["packages"].get("node_modules/" + name)
        if not isinstance(record, dict) or record.get("version") != manifest.get("version"):
            raise ValueError("顶层依赖与安装锁记录不符")
        bins = manifest.get("bin", {})
        if isinstance(bins, str):
            bins = {name.rsplit("/", 1)[-1]: bins}
        for command, entry in bins.items():
            target = manifest_path.parent / entry
            try:
                target.resolve().relative_to(modules.resolve())
            except (ValueError, OSError, RuntimeError):
                raise RuntimeError("依赖入口越过 node_modules 边界") from None
            shim = modules / ".bin" / (command + (".cmd" if sys.platform == "win32" else ""))
            if not target.is_file() or not shim.is_file():
                raise ValueError("顶层依赖命令入口不完整")
        manifests[name] = digest(manifest_path.read_bytes())
    return digest(encoded({"hidden_lock": digest(hidden.read_bytes()), "manifests": manifests}))


def ensure(root):
    started = time.monotonic()
    root = Path(root).resolve()
    npm = shutil.which("npm.cmd" if sys.platform == "win32" else "npm")
    node = shutil.which("node")
    if not npm or not node:
        raise RuntimeError("找不到 Node/npm")
    modules = root / "node_modules"
    safe_tree(modules)
    key = identity(root, npm, node)
    marker = modules / MARKER
    reason = "缺少成功安装标记"
    try:
        previous = json.loads(marker.read_text(encoding="utf-8"))
        if not isinstance(previous, dict):
            raise ValueError("安装标记无效")
        if previous.get("schema") != SCHEMA or previous.get("key") != key:
            reason = "依赖或 Node/npm 安装环境已变化"
        elif previous.get("health") != health(root):
            reason = "依赖安装记录已变化"
        else:
            print("前端依赖缓存命中：key=%s，耗时 %.2f 秒" % (key[:12], time.monotonic() - started), flush=True)
            return
    except (OSError, ValueError, KeyError, TypeError):
        if marker.exists():
            reason = "安装标记或依赖不完整"
    print("前端依赖缓存未命中：%s；key=%s" % (reason, key[:12]), flush=True)
    # 先撤销旧成功标记；失败/中断后绝不误认为这次安装成功。
    if marker.exists():
        marker.unlink()
    result = subprocess.run([npm, *INSTALL_ARGS], cwd=root, check=False)
    if result.returncode:
        if marker.exists():
            marker.unlink()
        raise RuntimeError("npm ci 失败（退出码 %s），未保留有效缓存标记" % result.returncode)
    safe_tree(modules)
    installed = health(root)
    if identity(root, npm, node) != key:
        raise RuntimeError("安装期间依赖配置发生变化，拒绝写入缓存标记")
    marker.write_text(json.dumps({"schema": SCHEMA, "key": key, "health": installed}) + "\n", encoding="utf-8")
    print("前端依赖安装完成：key=%s，耗时 %.2f 秒" % (key[:12], time.monotonic() - started), flush=True)


def main():
    try:
        ensure(Path.cwd())
    except (OSError, ValueError, RuntimeError) as error:
        print("前端依赖准备失败：%s" % error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
